-- Миграция: добавляем status в friendships — переход от мгновенной
-- дружбы к заявкам ('pending' → 'accepted').
-- Применить вручную через psql к уже существующей базе.
--
-- DEFAULT 'accepted', а не 'pending': у уже существующих в таблице
-- записей дружба уже состоялась (их создавали как мгновенную, до этой
-- миграции) — задним числом переводить их в "ожидает подтверждения"
-- было бы поведенческим регрессом для текущих пользователей, которые
-- уже считают друг друга друзьями. Новые заявки сервер (POST /friendships,
-- см. server.js) будет создавать явно со status='pending', не полагаясь
-- на этот DEFAULT — он нужен только для уже существующих строк.

ALTER TABLE friendships
  ADD COLUMN status TEXT NOT NULL DEFAULT 'accepted';
