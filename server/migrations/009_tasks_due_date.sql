-- Миграция: добавляем due_date в tasks.
-- Применить вручную через psql к уже существующей базе (schema.sql
-- этого не сделает — CREATE TABLE IF NOT EXISTS не трогает существующие
-- таблицы).
--
-- КОРЕНЬ БАГА "дата окончания не отображается сразу после создания":
-- у задач такой колонки не было вообще. Фронт (project-detail.component.ts)
-- уже давно шлёт dueDate при создании/редактировании задачи и рисует по
-- ней бейджи/фильтры — но server.js эти данные тихо отбрасывал (их не было
-- ни в TASK_COLUMNS, ни в TASKS_SELECT, ни, тем более, в самой таблице).
-- То, что дата как будто "появлялась после повторного редактирования" —
-- иллюзия: инлайн-редактирование (saveEdit()) писало task.dueDate прямо
-- в памяти браузера, не дожидаясь и не проверяя ответ сервера. После
-- обновления страницы значение пропадало снова, потому что в базе его
-- никогда и не было.
--
-- Без DEFAULT и без NOT NULL — как completed_at (см. миграцию 005) и
-- due_date у projects: задача не обязана иметь срок.

ALTER TABLE tasks
  ADD COLUMN due_date DATE;
