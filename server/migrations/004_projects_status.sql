-- Миграция: добавляем status в projects.
-- Применить вручную через psql к уже существующей базе (schema.sql
-- этого не сделает — CREATE TABLE IF NOT EXISTS не трогает существующие
-- таблицы).
--
-- DEFAULT 'active' нужен по двум причинам:
--  1) у уже существующих в таблице проектов должно появиться осмысленное
--     значение, а не NULL (в паре с NOT NULL без DEFAULT ALTER бы вообще
--     упал на непустой таблице);
--  2) это то же значение, которое фронт проставляет при создании нового
--     проекта (project-list.component.ts, createProject()), так что
--     поведение "проект без явного статуса — активный" совпадает
--     что на бэкенде, что на фронте.

ALTER TABLE projects
  ADD COLUMN status TEXT NOT NULL DEFAULT 'active';
