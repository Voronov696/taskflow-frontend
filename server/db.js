// Модуль подключения к PostgreSQL.
// Здесь и только здесь мы создаём Pool — все остальные файлы (server.js)
// должны использовать экспортируемую функцию query(), а не лезть в pg напрямую.

// dotenv.config() читает файл .env и раскладывает его строки по
// process.env — именно оттуда pg дальше и возьмёт настройки подключения.
// Вызываем здесь же (а не только в server.js), чтобы db.js был
// самодостаточным и работал, даже если его когда-нибудь подключат
// откуда-то ещё раньше, чем настроится server.js.
require('dotenv').config();

const { Pool, types } = require('pg');

// По умолчанию pg конвертирует колонки типа DATE (OID 1082) в JS Date —
// а при JSON.stringify() (res.json() в server.js) такой Date уходит клиенту
// как ISO-строка со временем и таймзоной ("...T22:00:00.000Z"), из-за чего
// день может сдвинуться, а фронт (formatDueDate/toLocalMidnight — они ждут
// чистый "YYYY-MM-DD" и делают dateStr.split('-')) получает "Invalid Date".
// Отключаем эту конвертацию — DATE отдаётся как есть, строкой "YYYY-MM-DD",
// без времени и часового пояса. Чинит due_date у tasks/projects и
// completed_at у tasks разом, одним местом.
types.setTypeParser(1082, (val) => val);

// Pool — это "пул" (набор) уже открытых соединений с базой данных.
// Открывать новое TCP-соединение с PostgreSQL на каждый запрос дорого
// (это медленно и создаёт лишнюю нагрузку на базу), поэтому вместо этого
// Pool держит несколько соединений открытыми заранее и переиспользует их:
// когда мы вызываем pool.query(), он берёт свободное соединение из пула,
// выполняет запрос и возвращает соединение обратно в пул для следующего запроса.
//
// Два способа подключиться, в зависимости от того, где мы бежим:
//
// - Облако (Railway и подобные) даёт БД не отдельными полями, а одной
//   строкой подключения в DATABASE_URL — если она есть, используем
//   connectionString. Управляемые Postgres на облачных хостингах почти
//   всегда требуют SSL, но с самоподписанным/непубличным сертификатом
//   в цепочке доверия — rejectUnauthorized: false отключает именно
//   проверку цепочки, а не шифрование само по себе (шифрование остаётся).
//
// - Локально DATABASE_URL не задана — тогда, как и раньше, `new Pool()`
//   без аргументов, и pg сам читает переменные PGHOST, PGPORT, PGUSER,
//   PGPASSWORD, PGDATABASE из server/.env (загружены строкой выше через
//   dotenv). Локальный Postgres слушает без SSL, поэтому здесь его не
//   включаем.
const pool = process.env.DATABASE_URL
  ? new Pool({
      connectionString: process.env.DATABASE_URL,
      ssl: { rejectUnauthorized: false },
    })
  : new Pool();

// Оборачиваем pool.query в свою функцию query() — это единая точка входа
// для SQL-запросов из всего приложения. Если в будущем понадобится,
// например, логировать все запросы или менять способ подключения —
// достаточно поменять это место, а не каждый файл с маршрутами.
function query(text, params) {
  // text — строка SQL с плейсхолдерами $1, $2, ...
  // params — массив значений, которые pg сам безопасно подставит
  // вместо этих плейсхолдеров (см. объяснение про параметризованные
  // запросы в чате).
  return pool.query(text, params);
}

module.exports = { query };
