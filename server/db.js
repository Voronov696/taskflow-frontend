// Модуль подключения к PostgreSQL.
// Здесь и только здесь мы создаём Pool — все остальные файлы (server.js)
// должны использовать экспортируемую функцию query(), а не лезть в pg напрямую.

// dotenv.config() читает файл .env и раскладывает его строки по
// process.env — именно оттуда pg дальше и возьмёт настройки подключения.
// Вызываем здесь же (а не только в server.js), чтобы db.js был
// самодостаточным и работал, даже если его когда-нибудь подключат
// откуда-то ещё раньше, чем настроится server.js.
require('dotenv').config();

const { Pool } = require('pg');

// Pool — это "пул" (набор) уже открытых соединений с базой данных.
// Открывать новое TCP-соединение с PostgreSQL на каждый запрос дорого
// (это медленно и создаёт лишнюю нагрузку на базу), поэтому вместо этого
// Pool держит несколько соединений открытыми заранее и переиспользует их:
// когда мы вызываем pool.query(), он берёт свободное соединение из пула,
// выполняет запрос и возвращает соединение обратно в пул для следующего запроса.
//
// Явные параметры (host/port/user/password/database) не передаём —
// у pg есть "магия" по умолчанию: если создать `new Pool()` без
// аргументов, библиотека сама читает переменные окружения
// PGHOST, PGPORT, PGUSER, PGPASSWORD, PGDATABASE — а они у нас уже
// лежат в server/.env и загружены строкой выше через dotenv.
const pool = new Pool();

// Оборачиваем pool.query в свою функцию query() — это единая точка входа
// для SQL-запросов из всего приложения. Если в будущем понадобится,
// например, логировать все запросы или менять способ подключения —
// достаточно поменять это место, а не каждый файл с маршрутами.
function query(text, params) {
  // text — строка SQL с плейсхолдерами $1, $2, ...
  // params — массив значений, которые pg сам безопасно подставит
  // вместо этих плейсхолдеров (см. объяснение про параметризованные
  // запросы в чате).
  return pool.query(text, params);
}

module.exports = { query };
